using ShipLean.Contracts.Boards;
using ShipLean.Contracts.Persisted;

namespace ShipLean.Contracts.Views;

// GET of a level board. Filters (assignee, tags, text and so on) are query parameters of this GET, applied on the server before
// the Done column is truncated to its most recent cards; the client never filters. A filtered-out card is absent from Cells but
// still counts in BoardColumnDto.Count (toward WIP) and in BoardColumnDto.HiddenCount. StyleRules, CardFields and Annotations are
// the board's settings as stored, so the client can draw a card without a second request. Lanes holds the stored lanes, or the generated By-Epic lanes (empty Epics included, No Epic last)
// when the Features board is laid out by Epic, or one lane when lanes are off. Cells cover every column of every lane.
public sealed record BoardViewDto(
    Guid BoardId,
    Guid ProjectId,
    BoardLevel Level,
    int OpenCount,
    decimal OpenPoints,
    IReadOnlyList<BoardColumnDto> Columns,
    IReadOnlyList<BoardLaneDto> Lanes,
    IReadOnlyList<StyleRuleJson> StyleRules,
    IReadOnlyList<CardFieldSettingJson> CardFields,
    CardAnnotationsJson Annotations);
